export function localizeCourseMetadata(
  locale: CourseMetadataLocale,
  slug: string,
  fallbackTitle: string,
  fallbackDescription: string
): Metadata {
  if (locale === "en")
    return { title: fallbackTitle, description: fallbackDescription };
  const title = titleMaps[locale]?.[slug] ?? fallbackTitle;
  return { title, description: `${descriptionLead[locale]} ${title}。` };
}

